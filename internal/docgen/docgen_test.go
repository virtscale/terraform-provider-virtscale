// repoRoot is the module root, two levels up from this package.
const repoRoot = "../.."

// The generated documentation in docs/ is what the schemas say: a schema, an example or a template that changed without
// `go generate ./...` shows up here as a difference.
func TestDocsAreGenerated(t *testing.T) {
	want, err := Generate(repoRoot)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if len(want) < 15 {
		t.Fatalf("Generate made %d files, want a page per resource and data source, the index and the guide", len(want))
	}
	for name, content := range want {
		got, err := os.ReadFile(filepath.Join(repoRoot, name))
		if err != nil {
			t.Errorf("%s is missing: run `go generate ./...` and commit docs/", name)
			continue
		}
		if string(got) != content {
			t.Errorf("%s is not what the schema makes of it: run `go generate ./...` and commit docs/", name)
		}
	}
	// Nothing in docs/ that is not generated (a page of a removed resource).
	_ = filepath.WalkDir(filepath.Join(repoRoot, "docs"), func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(repoRoot, path)
		if _, ok := want[filepath.ToSlash(rel)]; !ok {
			t.Errorf("%s is not generated by any schema: delete it", rel)
		}
		return nil
	})
}

func typeNames(t *testing.T) (resources, dataSources []string) {
	t.Helper()
	ctx := context.Background()
	p := vsprovider.New("dev")()
	for _, f := range p.Resources(ctx) {
		r := f()
		var resp resource.MetadataResponse
		r.Metadata(ctx, resource.MetadataRequest{ProviderTypeName: "virtscale"}, &resp)
		resources = append(resources, resp.TypeName)
	}
	for _, f := range p.DataSources(ctx) {
		d := f()
		var resp datasource.MetadataResponse
		d.Metadata(ctx, datasource.MetadataRequest{ProviderTypeName: "virtscale"}, &resp)
		dataSources = append(dataSources, resp.TypeName)
	}
	sort.Strings(resources)
	sort.Strings(dataSources)
	return
}

// Every resource has an example and an import command, every data source an example; the files exist and are not empty.
func TestEveryResourceAndDataSourceHasAnExample(t *testing.T) {
	resources, dataSources := typeNames(t)
	if len(resources) < 8 || len(dataSources) < 6 {
		t.Fatalf("found %d resources and %d data sources, want at least 8 and 6", len(resources), len(dataSources))
	}
	need := []string{filepath.Join(repoRoot, "examples", "provider", "provider.tf"), filepath.Join(repoRoot, "examples", "complete", "main.tf")}
	for _, r := range resources {
		need = append(need, filepath.Join(repoRoot, "examples", "resources", r, "resource.tf"), filepath.Join(repoRoot, "examples", "resources", r, "import.sh"))
	}
	for _, d := range dataSources {
		need = append(need, filepath.Join(repoRoot, "examples", "data-sources", d, "data-source.tf"))
	}
	for _, f := range need {
		if b, err := os.ReadFile(f); err != nil || len(strings.TrimSpace(string(b))) == 0 {
			t.Errorf("%s is missing or empty", f)
		}
	}
}

// The examples hold no literal credential: variables, the environment, or a sensitive variable.
func TestExamplesHoldNoSecrets(t *testing.T) {
	secret := regexp.MustCompile(`vsk_|PRIVATE KEY|api_key\s*=\s*"|secret_access_key\s*=\s*"|password\s*=\s*"`)
	_ = filepath.WalkDir(filepath.Join(repoRoot, "examples"), func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		if b, _ := os.ReadFile(path); secret.Match(b) {
			t.Errorf("%s looks like it holds a credential", path)
		}
		return nil
	})
}

// openTofu is the tofu to validate with, or a skip.
func openTofu(t *testing.T) string {
	t.Helper()
	if p := os.Getenv("TF_ACC_TERRAFORM_PATH"); p != "" {
		return p
	}
	p, err := exec.LookPath("tofu")
	if err != nil {
		t.Skip("tofu is not on PATH; the examples are validated in CI")
	}
	return p
}

// validateDir runs `tofu validate -json` in dir with the locally built provider (dev_overrides, no init) and returns the
// error diagnostics, one line each.
func validateDir(t *testing.T, tofu, tfrc, dir string) []string {
	t.Helper()
	cmd := exec.Command(tofu, "validate", "-json", "-no-color")
	cmd.Dir = dir
	cmd.Env = append(cleanEnv(), "TF_CLI_CONFIG_FILE="+tfrc, "TF_IN_AUTOMATION=1")
	out, _ := cmd.Output()
	var result struct {
		Valid       bool `json:"valid"`
		Diagnostics []struct {
			Severity string `json:"severity"`
			Summary  string `json:"summary"`
			Detail   string `json:"detail"`
		} `json:"diagnostics"`
	}
	if err := json.Unmarshal(out, &result); err != nil {
		return []string{"tofu validate gave no JSON: " + strings.TrimSpace(string(out))}
	}
	var problems []string
	for _, d := range result.Diagnostics {
		if d.Severity == "error" {
			problems = append(problems, d.Summary+": "+d.Detail)
		}
	}
	if !result.Valid && len(problems) == 0 {
		problems = append(problems, "not valid")
	}
	return problems
}

// cleanEnv is the environment without anything that could point tofu or the provider at a real API.
func cleanEnv() []string {
	var env []string
	for _, kv := range os.Environ() {
		if strings.HasPrefix(kv, "VIRTSCALE_") || strings.HasPrefix(kv, "TF_CLI_CONFIG_FILE=") {
			continue
		}
		env = append(env, kv)
	}
	return env
}

// Every example validates against the provider built from this tree, and a broken example does not: the check is real.
func TestExamplesValidate(t *testing.T) {
	tofu := openTofu(t)
	work := t.TempDir()
	bin := filepath.Join(work, "bin")
	if err := os.MkdirAll(bin, 0o755); err != nil {
		t.Fatal(err)
	}
	build := exec.Command("go", "build", "-o", filepath.Join(bin, "terraform-provider-virtscale"), ".")
	build.Dir = repoRoot
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("building the provider: %v\n%s", err, out)
	}
	// OpenTofu resolves virtscale/virtscale against registry.opentofu.org, Terraform against registry.terraform.io.
	tfrc := filepath.Join(work, "dev.tfrc")
	rc := "provider_installation {\n  dev_overrides {\n    \"registry.opentofu.org/virtscale/virtscale\" = \"" + bin + "\"\n    \"registry.terraform.io/virtscale/virtscale\" = \"" + bin + "\"\n  }\n  direct {}\n}\n"
	if err := os.WriteFile(tfrc, []byte(rc), 0o600); err != nil {
		t.Fatal(err)
	}

	// each .tf file or directory of .tf files under examples/, in a directory of its own
	groups := map[string][]string{}
	_ = filepath.WalkDir(filepath.Join(repoRoot, "examples"), func(path string, d os.DirEntry, err error) error {
		if err == nil && !d.IsDir() && strings.HasSuffix(path, ".tf") {
			groups[filepath.Dir(path)] = append(groups[filepath.Dir(path)], path)
		}
		return nil
	})
	if len(groups) < 15 {
		t.Fatalf("found %d example directories, want one per resource and data source and more", len(groups))
	}
	preamble := "terraform {\n  required_providers {\n    virtscale = {\n      source = \"virtscale/virtscale\"\n    }\n  }\n}\n"
	prepare := func(files []string, name string) string {
		dir := filepath.Join(work, "ex", name)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
		hasProviders := false
		for _, f := range files {
			b, err := os.ReadFile(f)
			if err != nil {
				t.Fatal(err)
			}
			hasProviders = hasProviders || strings.Contains(string(b), "required_providers")
			if err := os.WriteFile(filepath.Join(dir, filepath.Base(f)), b, 0o600); err != nil {
				t.Fatal(err)
			}
		}
		if !hasProviders {
			if err := os.WriteFile(filepath.Join(dir, "versions_for_validate.tf"), []byte(preamble), 0o600); err != nil {
				t.Fatal(err)
			}
		}
		return dir
	}
	for dir, files := range groups {
		rel, _ := filepath.Rel(filepath.Join(repoRoot, "examples"), dir)
		t.Run(filepath.ToSlash(rel), func(t *testing.T) {
			if problems := validateDir(t, tofu, tfrc, prepare(files, strings.ReplaceAll(filepath.ToSlash(rel), "/", "_"))); len(problems) > 0 {
				t.Errorf("does not validate:\n%s", strings.Join(problems, "\n"))
			}
		})
	}

	t.Run("a broken example is refused", func(t *testing.T) {
		dir := filepath.Join(work, "ex", "broken")
		_ = os.MkdirAll(dir, 0o755)
		broken := preamble + "\nresource \"virtscale_project\" \"x\" {\n  name = \"web\"\n  no_such_attribute = true\n}\n"
		_ = os.WriteFile(filepath.Join(dir, "main.tf"), []byte(broken), 0o600)
		if problems := validateDir(t, tofu, tfrc, dir); len(problems) == 0 {
			t.Error("a configuration with an unknown attribute validated: the check proves nothing")
		}
	})
}

// The guide names every sensitive attribute of the provider, and only those: it is generated from the schemas.
func TestTheGuideListsTheSensitiveAttributesOfTheSchemas(t *testing.T) {
	pages, err := Generate(repoRoot)
	if err != nil {
		t.Fatal(err)
	}
	guide := pages["docs/guides/state-secrets-and-import.md"]
	for _, want := range []string{"virtscale_s3_access_key.secret_access_key", "provider.api_key", "encrypted backend"} {
		if !strings.Contains(guide, want) {
			t.Errorf("the guide does not mention %q", want)
		}
	}
	if strings.Contains(guide, "virtscale_ssh_key.public_key") {
		t.Error("the guide lists a public key as sensitive")
	}
}
