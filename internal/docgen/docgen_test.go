// The id an import.sh shows is the shape the resource's ImportState takes: a bare id is refused by exactly the resources
// whose example shows an id of two parts, and those take "a/b".
func TestTheImportIDsOfTheExamplesAreWhatImportStateTakes(t *testing.T) {
	ctx := context.Background()
	p := vsprovider.New("dev")()
	n := 0
	for _, newResource := range p.Resources(ctx) {
		r := newResource()
		var meta resource.MetadataResponse
		r.Metadata(ctx, resource.MetadataRequest{ProviderTypeName: "virtscale"}, &meta)
		var rs resource.SchemaResponse
		r.Schema(ctx, resource.SchemaRequest{}, &rs)
		importer, ok := r.(resource.ResourceWithImportState)
		if !ok {
			t.Errorf("%s cannot be imported", meta.TypeName)
			continue
		}
		takes := func(id string) bool {
			resp := resource.ImportStateResponse{State: tfsdk.State{Schema: rs.Schema, Raw: tftypes.NewValue(rs.Schema.Type().TerraformType(ctx), nil)}}
			importer.ImportState(ctx, resource.ImportStateRequest{ID: id}, &resp)
			return !resp.Diagnostics.HasError()
		}
		shown := importID(read(repoRoot, "examples/resources/"+meta.TypeName+"/import.sh"))
		if !strings.HasPrefix(shown, "<") || !strings.HasSuffix(shown, ">") {
			t.Errorf("%s: the import.sh shows %q, want an id in <angle brackets>", meta.TypeName, shown)
			continue
		}
		twoParts := strings.Contains(shown, "/")
		if got := !takes("one-part-id"); got != twoParts {
			t.Errorf("%s: the import.sh shows %q, but a one-part id is refused by ImportState: %v", meta.TypeName, shown, got)
		}
		if twoParts && !takes("parent-id/own-id") {
			t.Errorf("%s: the import.sh shows %q, but ImportState refuses \"parent-id/own-id\"", meta.TypeName, shown)
		}
		n++
	}
	if n < 8 {
		t.Errorf("checked %d resources, want all 8", n)
	}
}

// isGuide reports whether a docs-relative path (forward slashes) is a page of docs/guides.
func isGuide(rel string) bool {
	name, ok := strings.CutPrefix(rel, "docs/guides/")
	return ok && strings.HasSuffix(name, ".md") && !strings.Contains(name, "/")
}

// guidePages is every page of docs/guides on disk by file name, the generated one included.
func guidePages(t *testing.T) map[string]string {
	t.Helper()
	files, err := filepath.Glob(filepath.Join(repoRoot, "docs", "guides", "*.md"))
	if err != nil || len(files) == 0 {
		t.Fatalf("no guides in docs/guides: %v", err)
	}
	pages := map[string]string{}
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		pages[filepath.Base(f)] = string(b)
	}
	return pages
}

// terraformBlocks is the content of each ```terraform fence of a page, the fence the registry highlights and the one a
// guide uses for a configuration that must validate (a CLI config or a shell session uses another word).
func terraformBlocks(page string) []string {
	var blocks []string
	for _, m := range regexp.MustCompile("(?ms)^```terraform\n(.*?)^```$").FindAllStringSubmatch(page, -1) {
		blocks = append(blocks, m[1])
	}
	return blocks
}

func TestTerraformBlocksTakesOnlyTheTerraformFence(t *testing.T) {
	page := "text\n\n```terraform\nA\n```\n\n```hcl\nB\n```\n\n```terraform\nC\nD\n```\n"
	got := terraformBlocks(page)
	if len(got) != 2 || got[0] != "A\n" || got[1] != "C\nD\n" {
		t.Errorf("terraformBlocks = %q, want the two terraform fences only", got)
	}
}

// The guides a person wrote (everything in docs/guides but the generated page) are what the registry renders: each has
// the front matter it reads, a title heading, and none holds a credential. The three guides a new user starts from exist.
func TestHandWrittenGuides(t *testing.T) {
	pages := guidePages(t)
	generated, err := Generate(repoRoot)
	if err != nil {
		t.Fatal(err)
	}
	for _, need := range []string{"installation.md", "authentication.md", "getting-started.md"} {
		if _, ok := pages[need]; !ok {
			t.Errorf("docs/guides/%s is missing", need)
		}
	}
	realKey := regexp.MustCompile(`vsk_[0-9a-fA-F]{8}-|PRIVATE KEY`)
	for name, page := range pages {
		if _, ok := generated["docs/guides/"+name]; ok {
			continue
		}
		head, _, found := strings.Cut(strings.TrimPrefix(page, "---\n"), "\n---\n")
		if !strings.HasPrefix(page, "---\n") || !found {
			t.Errorf("%s has no front matter", name)
			continue
		}
		title, description, ok := frontMatter(page)
		if !ok || title == "" || description == "" {
			t.Errorf("%s: front matter needs page_title and description (got %q, %q)", name, title, description)
		}
		if !strings.Contains(head, "\nsubcategory: ") {
			t.Errorf("%s: front matter has no subcategory", name)
		}
		if !strings.Contains(page, "\n# ") {
			t.Errorf("%s has no # heading", name)
		}
		if realKey.MatchString(page) {
			t.Errorf("%s holds what looks like a real API key or a private key", name)
		}
		for i, block := range terraformBlocks(page) {
			if credentialRE.MatchString(block) {
				t.Errorf("%s: terraform block %d holds a literal credential", name, i+1)
			}
		}
	}
}

// Every ```terraform block of a hand-written guide is a complete configuration that validates against the provider built
// from this tree, the way TestExamplesValidate checks the examples. A guide shows a fragment or a CLI config in another
// fence (hcl, shell), so nothing a reader pastes is half a file.
func TestGuideBlocksValidate(t *testing.T) {
	tofu := openTofu(t)
	work := t.TempDir()
	tfrc := devProvider(t, work)
	generated, err := Generate(repoRoot)
	if err != nil {
		t.Fatal(err)
	}
	total := 0
	for name, page := range guidePages(t) {
		if _, ok := generated["docs/guides/"+name]; ok {
			continue
		}
		blocks := terraformBlocks(page)
		if len(blocks) == 0 {
			t.Errorf("%s has no terraform block", name)
		}
		for i, block := range blocks {
			total++
			t.Run(fmt.Sprintf("%s/%d", strings.TrimSuffix(name, ".md"), i+1), func(t *testing.T) {
				dir := filepath.Join(work, "guides", fmt.Sprintf("%s_%d", strings.TrimSuffix(name, ".md"), i+1))
				if err := os.MkdirAll(dir, 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(filepath.Join(dir, "main.tf"), []byte(block), 0o600); err != nil {
					t.Fatal(err)
				}
				if !strings.Contains(block, "required_providers") {
					if err := os.WriteFile(filepath.Join(dir, "versions_for_validate.tf"), []byte(preamble), 0o600); err != nil {
						t.Fatal(err)
					}
				}
				if problems := validateDir(t, tofu, tfrc, dir); len(problems) > 0 {
					t.Errorf("does not validate:\n%s", strings.Join(problems, "\n"))
				}
			})
		}
	}
	if total < 5 {
		t.Errorf("validated %d guide blocks, want at least 5: the extraction may have matched nothing", total)
	}
}

